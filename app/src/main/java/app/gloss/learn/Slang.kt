    private val byTerm = terms.associateBy { it.term }

    fun forWord(surface: String, base: String): SlangTerm? = byTerm[surface] ?: byTerm[base]

    /** Every slang term the passage contains, longest first, without ones inside a longer hit. */
    fun inText(text: String): List<SlangTerm> {
        val hits = terms.filter { text.contains(it.term) }.sortedByDescending { it.term.length }
        return hits.filterNot { h -> hits.any { it !== h && it.term.length > h.term.length && it.term.contains(h.term) } }
    }
