"""Builds Gloss's icon and wordmark from the bundled fonts.

Writes the adaptive launcher icon layers into app/src/main/res/drawable and SVG
versions into docs/brand/svg. Run from the repo root:

    python3 docs/brand/build.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from glyphs import outline  # noqa: E402

RES = "app/src/main/res/drawable"
SVG = "docs/brand/svg"

# Pigments (keep in sync with ui/theme/Gloss.kt).
LAPIS = "#2338C2"
LAPIS_LIGHT = "#3149DD"
LAPIS_DEEP = "#141E78"
NIGHT = "#070A1C"
GOLD_HI = "#F6D886"
GOLD = "#E3B341"
GOLD_LO = "#B98320"
INK = "#0B0D1C"
WHITE = "#FFFFFF"


def tidy(d):
    """Round path numbers to two decimals so vector drawables stay small."""
    def r(m):
        v = round(float(m.group(0)), 2)
        s = f"{v:.2f}".rstrip("0").rstrip(".")
        return "0" if s in ("-0", "") else s
    return re.sub(r"-?\d+\.?\d*(?:e-?\d+)?", r, d)


def skew_bar(x, y, w, h, slant=0.21):
    """A gold-leaf bar: a parallelogram leaning like the italic, with clipped ends."""
    dx = h * slant
    return tidy(f"M{x + dx} {y}L{x + w + dx} {y}L{x + w} {y + h}L{x} {y + h}Z")


# ---- The mark: an italic g with a gold-leaf gloss under its bowl -------------------

def mark(cx, cy, height):
    """Returns (glyph_d, bar_d) for the mark centred on (cx, cy), `height` tall."""
    # Instrument Serif Italic 'g' at size 100 spans y -59.8..21.6 (81.4 tall).
    size = 100 * height / 81.4
    _, adv, (x0, y0, x1, y1) = outline("g", size)
    gx = cx - (x0 + x1) / 2
    gy = cy - (y0 + y1) / 2
    d, _, (bx0, by0, bx1, by1) = outline("g", size, x=gx, baseline=gy)
    # The bar sits on the baseline (y=gy), under the bowl, a touch wider than it.
    bar_h = height * 0.1
    bar = skew_bar(bx0 - height * 0.10, gy - bar_h * 0.15, (bx1 - bx0) * 1.02, bar_h)
    return tidy(d), bar


def gold_gradient_xml(x1, y1, x2, y2):
    return f"""
            <aapt:attr name="android:fillColor">
                <gradient android:type="linear" android:startX="{x1}" android:startY="{y1}" android:endX="{x2}" android:endY="{y2}">
                    <item android:offset="0" android:color="#FF{GOLD_HI[1:]}" />
                    <item android:offset="0.55" android:color="#FF{GOLD[1:]}" />
                    <item android:offset="1" android:color="#FF{GOLD_LO[1:]}" />
                </gradient>
            </aapt:attr>"""


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text)
    print("wrote", path)


